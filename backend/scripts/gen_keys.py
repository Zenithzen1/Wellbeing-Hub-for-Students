"""Fresh secrets for .env (plan section 14). Run from backend/:

    python scripts/gen_keys.py > ../.env

stdout gets HMAC_KEY, JWT_SECRET and VAULT_PUBLIC_KEY. The custodian's vault PRIVATE key goes to
stderr only, once: copy it somewhere safe and offline. It is never written to .env or the database,
and without it no vault row can ever be opened.

Never rotate HMAC_KEY casually: a new key gives every student a new pseudonym.
"""

import secrets
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.auth import generate_vault_keys  # noqa: E402


def main() -> None:
    public, private = generate_vault_keys()
    print("# Generated by scripts/gen_keys.py. Never commit this file.")
    print("DATABASE_URL=sqlite:///./hub.db")
    print(f"HMAC_KEY={secrets.token_hex(32)}")
    print(f"JWT_SECRET={secrets.token_hex(32)}")
    print(f"VAULT_PUBLIC_KEY={public}")
    print("SCHEDULER_INTERVAL_SECONDS=15")
    print("\nCUSTODIAN VAULT PRIVATE KEY (shown once; keep it offline, not in .env):", file=sys.stderr)
    print(private, file=sys.stderr)


if __name__ == "__main__":
    main()
